create table if not exists public.students (
  id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  date_of_birth date not null,
  grade text not null,
  arabic_level text,
  health_information text,
  special_considerations text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.parents (
  id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  email text not null,
  phone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.student_parents (
  student_id bigint not null references public.students (id),
  parent_id bigint not null references public.parents (id),
  relationship text not null,
  primary key (student_id, parent_id)
);

create table if not exists public.groups (
  id bigint generated by default as identity primary key,
  name text not null,
  minimum_grade text not null,
  maximum_grade text not null,
  capacity integer not null,
  created_at timestamptz not null default now()
);

create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students (id),
  school_year text not null,
  status text not null default 'pending',
  is_returning boolean not null default false,
  group_id bigint references public.groups (id),
  registered_at timestamptz not null default now()
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  registration_id bigint not null references public.registrations (id),
  amount numeric not null,
  status text not null default 'pending',
  payment_method text,
  transaction_id text,
  paid_at timestamptz,
  created_at timestamptz not null default now()
);
